"""LaTeX export: a compilable .tex rendering of the document.

The goal is a clean, ordinary article -- the kind of file a LaTeX-literate
reviewer can recompile without surprises. Everything user-typed is escaped,
fonts map to the standard Helvetica/Times pairs, and margins follow the
resume's own spacing settings.
"""

from __future__ import annotations

import re

from .schemas import PaperSize, ResumeDocument

# Sans faces ride on Helvetica, serifs on Times; both ship with every TeX
# distribution, which matters more than exact brand matching here.
_SANS = "\\usepackage{helvet}\n\\renewcommand{\\familydefault}{\\sfdefault}"
_SERIF = "\\usepackage{newtxtext}"

_GEOMETRY = {PaperSize.A4: "a4paper", PaperSize.LETTER: "letterpaper"}


def _escape(text: str) -> str:
    """Escape the ten characters TeX treats specially."""
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    out = text
    # Backslash first so it does not double-escape the replacements themselves.
    for char in ("\\", "&", "%", "$", "#", "_", "{", "}", "~", "^"):
        out = out.replace(char, replacements[char])
    return out


def _href(url: str) -> str:
    """Clickable \\href whose target gets a scheme the author may have omitted."""
    target = url if re.match(r"^https?://", url, re.I) else f"https://{url}"
    return f"\\href{{{_escape(target)}}}{{{_escape(url)}}}"


def _date_range(start: str, end: str, current: bool = False) -> str:
    to = "Present" if current else end.strip()
    if not start.strip() and not to:
        return ""
    if not start.strip():
        return _escape(to)
    if not to:
        return _escape(start)
    return f"{_escape(start)} -- {_escape(to)}"


def _item_head(title: str, sub: str, meta: str, date: str) -> str:
    head = f"\\textbf{{{_escape(title)}}}" if title else ""
    rest = " \u00b7 ".join(p for p in (sub, meta) if p)
    line = head
    if head and rest:
        line += f" \\textmd{{--}} {rest}"
    elif rest:
        line += rest
    if date:
        line += f" \\hfill {{{date}}}"
    return f"{line}\\par\\medskip\n" if line.strip() else ""


def build_tex(document: ResumeDocument, paper_size: PaperSize = PaperSize.A4) -> str:
    basics = document.basics
    settings = document.settings

    sans_names = ("inter", "lato", "plex", "arial", "calibri", "helvetica", "roboto", "open sans")
    font_pkg = _SANS if any(s in settings.font_family.lower() for s in sans_names) else _SERIF

    margin = f"{settings.margin_y}mm {settings.margin_x}mm"
    out: list[str] = []
    out.append("% Generated by AgentCV -- compile with pdflatex")
    out.append("\\documentclass[10pt]{article}")
    out.append(f"\\usepackage[{_GEOMETRY[paper_size]}]{{geometry}}")
    out.append(f"\\geometry{{margin={margin}}}")
    out.append("\\usepackage[T1]{fontenc}")
    out.append(font_pkg)
    out.append("\\usepackage{enumitem}")
    out.append("\\setlist[itemize]{nosep, leftmargin=*, topsep=2pt}")
    out.append("\\usepackage[hidelinks]{hyperref}")
    out.append("\\pagestyle{empty}")
    out.append("\\setlength{\\parindent}{0pt}")
    out.append("")
    out.append("\\begin{document}")

    name = basics.full_name.strip()
    headline = basics.headline.strip()
    contact = [p.strip() for p in (basics.email, basics.phone, basics.location, basics.website) if p.strip()]
    links = [l.label.strip() or l.url.strip() for l in basics.links if (l.url.strip() or l.label.strip())]

    if name or headline or contact or links:
        out.append("\\begin{center}")
        out.append(f"  {{\\LARGE \\textbf{{{_escape(name)}}}}}\\\\[2pt]")
        if headline:
            out.append(f"  {{\\large {_escape(headline)}}}\\\\[3pt]")
        line = [l for l in contact if l]
        for link in links:
            if link not in line:
                line.append(link)
        if line:
            out.append("  " + _escape(" \u00b7 ".join(line)))
        out.append("\\end{center}")

    for section in document.sections:
        if not section.visible or not section.title.strip():
            continue
        items = [i for i in getattr(section, "items", []) if i.visible]
        if not items:
            continue

        out.append("")
        out.append(f"\\section*{{{_escape(section.title)}}}")

        if section.type == "summary":
            out.extend(_escape(i.summary.strip()) + "" for i in items if i.summary.strip())
        elif section.type == "skills":
            if getattr(section, "layout", "inline") == "bullets":
                seen: set[str] = set()
                flat: list[str] = []
                for group in items:
                    for skill in group.skills:
                        s = skill.strip()
                        if s and s not in seen:
                            seen.add(s)
                            flat.append(s)
                if flat:
                    out.append("\\begin{itemize}")
                    out.extend(f"  \\item {_escape(s)}" for s in flat)
                    out.append("\\end{itemize}")
            else:
                for group in items:
                    label = group.category.strip()
                    skills = ", ".join(s.strip() for s in group.skills if s.strip())
                    if not skills and not label:
                        continue
                    prefix = f"\\textbf{{{_escape(label)}}}: " if label else ""
                    out.append(f"{prefix}{_escape(skills)}")
        elif section.type == "languages":
            for item in items:
                level = f" --- {_escape(item.proficiency.strip())}" if item.proficiency.strip() else ""
                out.append(f"{_escape(item.name.strip())}{level}")
        elif section.type in {"experience", "education", "projects", "custom"}:
            for item in items:
                title = str(
                    getattr(item, "position", "") or getattr(item, "degree", "")
                    or getattr(item, "name", "") or getattr(item, "title", "")
                ).strip()
                sub = str(
                    getattr(item, "company", "") or getattr(item, "institution", "")
                    or getattr(item, "role", "") or getattr(item, "subtitle", "")
                ).strip()
                meta = str(
                    getattr(item, "location", "") or getattr(item, "grade", "") or ""
                ).strip()
                date = _date_range(
                    getattr(item, "start_date", ""), getattr(item, "end_date", ""), getattr(item, "current", False)
                )
                out.append(_item_head(title, _escape(sub), _escape(meta), date))
                bullets = [b.strip() for b in getattr(item, "bullets", []) if b.strip()]
                if bullets:
                    out.append("\\begin{itemize}")
                    out.extend(f"  \\item {_escape(b)}" for b in bullets)
                    out.append("\\end{itemize}")
                url = str(getattr(item, "url", "")).strip()
                if url:
                    out.append(_href(url))
        else:  # certifications
            for item in items:
                bits = [
                    str(p).strip()
                    for p in (getattr(item, "name", ""), getattr(item, "issuer", ""), getattr(item, "date", ""))
                    if str(p).strip()
                ]
                if bits:
                    out.append(_escape(" \u00b7 ".join(bits)))

    out.append("")
    out.append("\\end{document}")
    return "\n".join(out)
